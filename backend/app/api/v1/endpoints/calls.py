    """Updates composite risk score and broadcasts 'risk_update' to dashboard."""
    active = dashboard_event_bus.get_active_call(call_id)
    if active:
        active.update({
            "risk_score": risk.risk_score,
            "risk_level": risk.risk_level,
            "current_action": risk.action,
            "action": risk.action,
            "threat_signals": risk.signals,
            "contributing_signals": risk.contributing_signals,
        })

    user_id = active.get("user_id") if active else None

    await dashboard_event_bus.broadcast_event(
        event_type="risk_update",
        payload={
            "risk_score": risk.risk_score,
            "risk_level": risk.risk_level,
            "action": risk.action,
            "signals": risk.signals,
            "contributing_signals": risk.contributing_signals,
            "reason": risk.reason,
            "confidence": risk.confidence,
        },
        call_id=call_id,
        user_id=user_id
    )

    # Persist risk event to public.risk_events
    pool = await get_db_pool()
    if pool:
        try:
            async with pool.acquire() as conn:
                call_row = await conn.fetchrow("SELECT id FROM public.calls WHERE session_id = $1 LIMIT 1", call_id)
                if call_row:
                    import json
                    await conn.execute("""
                        INSERT INTO public.risk_events (
                            call_id, event_type, risk_score, risk_level, reason, confidence, contributing_signals
                        ) VALUES ($1, 'multi_signal_risk', $2, $3, $4, $5, $6::jsonb)
                    """, call_row["id"], risk.risk_score, risk.risk_level, risk.reason, risk.confidence, json.dumps(risk.contributing_signals))
                    await conn.execute("""
                        UPDATE public.calls SET overall_risk_score = $2, overall_risk_level = $3 WHERE id = $1
                    """, call_row["id"], risk.risk_score, risk.risk_level)
        except Exception as e:
            logger.debug(f"Failed to record risk_event: {e}")

    return {"status": "success", "call_id": call_id, "risk_score": risk.risk_score}

