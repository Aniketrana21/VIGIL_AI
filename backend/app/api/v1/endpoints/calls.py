@router.post("/{call_id}/terminate")
async def terminate_call(call_id: str, payload: TerminateCallRequest):
    """
    IMMEDIATE ENFORCEMENT ACTION: AUTOMATIC CALL TERMINATION.
    Executed when risk engine reaches CRITICAL threat with high confidence.
    Immediately signals call termination to audio stream, cuts session, logs audit, and updates dashboard.
    """
    logger.warning(f"🛑 ENFORCING AUTOMATIC CALL TERMINATION for session {call_id}: {payload.reason}")
    now = datetime.now(timezone.utc)

    active = dashboard_event_bus.get_active_call(call_id)
    if active:
        active["call_status"] = "TERMINATED"
        active["status"] = "TERMINATED"
        active["current_action"] = "TERMINATE"
        active["action"] = "TERMINATE"
        active["risk_score"] = payload.risk_score or 100
        active["risk_level"] = "CRITICAL"
        active["termination_reason"] = payload.reason
        active["ended_at"] = now.isoformat()

    # 1. Broadcast call_terminated event across WebSocket
    await dashboard_event_bus.broadcast_event(
        event_type="call_terminated",
        payload={
            "action": "TERMINATE",
            "risk_score": payload.risk_score or 100,
            "risk_level": "CRITICAL",
            "reason": payload.reason,
            "deepfake_probability": payload.deepfake_probability or (active.get("deepfake_probability") if active else 0.94),
            "speaker_similarity": payload.speaker_similarity or (active.get("speaker_similarity") if active else 0.28),
            "timestamp": now.isoformat(),
        },
        call_id=call_id
    )

    # 2. Persist audit record to Supabase PostgreSQL
    pool = await get_db_pool()
    if pool:
        try:
            async with pool.acquire() as conn:
                call_row = await conn.fetchrow("SELECT id FROM public.calls WHERE session_id = $1 LIMIT 1", call_id)
                if call_row:
                    c_id = call_row["id"]
                    # Add to call_actions
                    await conn.execute("""
                        INSERT INTO public.call_actions (
                            call_id, action, reason, risk_score, triggered_by, performed_at
                        ) VALUES ($1, 'TERMINATE', $2, $3, 'risk_engine_enforcement', $4)
                    """, c_id, payload.reason, payload.risk_score or 100, now)

                    # Update call record
                    await conn.execute("""
                        UPDATE public.calls
                        SET call_status = 'blocked',
                            final_action = 'BLOCK',
                            action_reason = $2,
                            overall_risk_score = $3,
                            overall_risk_level = 'CRITICAL',
                            ended_at = $4
                        WHERE id = $1
                    """, c_id, payload.reason, payload.risk_score or 100, now)
        except Exception as e:
            logger.warning(f"Error persisting call termination audit: {e}")

    return {
        "status": "TERMINATED",
        "call_id": call_id,
        "action": "TERMINATE",
        "reason": payload.reason,
        "enforced_at": now.isoformat()
    }

