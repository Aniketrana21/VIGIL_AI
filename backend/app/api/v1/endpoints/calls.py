@router.get("/{call_id}")
async def get_call_details(call_id: str):
    """Retrieves current live state and analysis metrics for a call session."""
    active = dashboard_event_bus.get_active_call(call_id)
    if active:
        return {**active, "status": active.get("status", active.get("call_status", "ACTIVE"))}

    pool = await get_db_pool()
    if pool:
        try:
            async with pool.acquire() as conn:
                row = await conn.fetchrow("SELECT * FROM public.calls WHERE session_id = $1 OR id::text = $1", call_id)
                if row:
                    return dict(row)
        except Exception as e:
            logger.warning(f"Error reading call {call_id} from DB: {e}")

    raise HTTPException(status_code=404, detail=f"Call session {call_id} not found")

