@router.post("/incoming", response_model=IncomingCallResponse, status_code=status.HTTP_200_OK)
async def handle_incoming_call(payload: IncomingCallRequest):
    """
    CRITICAL BEHAVIOR: UNIVERSAL INCOMING-CALL TRIGGER.
    VIGIL-AI activates for EVERY incoming call (unknown, known, saved contact, family, business).
    A known phone number is NEVER considered proof of legitimate speaker (SIM spoofing/hijack).
    Phone-number identity and voice identity are strictly separated.
    Captures metadata immediately, writes record to Supabase, and broadcasts 'incoming_call' to dashboard WebSocket.
    """
    call_id = payload.call_id or str(uuid.uuid4())
    raw_number = payload.phone_number
    normalized = caller_service.normalize_phone_number(raw_number)
    masked_phone = anonymize_caller_id(raw_number)
    now_iso = datetime.now(timezone.utc).isoformat()

    logger.info(f"🚨 UNIVERSAL INCOMING-CALL TRIGGER for {masked_phone} (call_id: {call_id}, contact_match: {payload.contact_match})")

    # Retrieve caller profile and history (isolated by user_id)
    caller = await caller_service.get_caller_by_number(
        phone_number=normalized,
        user_id=payload.user_id,
        display_name_hint=payload.caller_name,
        claimed_company=payload.company_name,
        claimed_relationship=payload.claimed_relationship
    )
    history = await call_history_service.get_history_summary(normalized, caller.id, user_id=payload.user_id)

    # Preliminary risk evaluation
    risk_assessment, recommended_action = risk_service.evaluate_preliminary_risk(
        caller=caller,
        history=history,
        stir_shaken_status=payload.stir_shaken_status or 0
    )

    contact_is_known = bool(
        payload.contact_match or 
        payload.contact_known or
        (payload.caller_type and payload.caller_type.lower() in ["contact", "saved_contact"]) or
        (caller.trust_status in ["contact", "trusted"]) or 
        (caller.caller_type and caller.caller_type.lower() in ["contact", "saved_contact"])
    )
    caller_display = payload.caller_name or caller.name or ("Known Contact" if contact_is_known else "Unknown Caller")

    # Platform capabilities delineation
    is_cellular = (payload.call_transport.upper() == "CELLULAR")
    cellular_audio_avail = False  # Explicit truth: cellular in-call audio not accessible on standard Android

    call_session_data = {
        "call_id": call_id,
        "session_id": call_id,
        "phone_number": raw_number,
        "normalized_phone_number": normalized,
        "masked_phone": masked_phone,
        "caller_name": caller_display,
        "company": caller.company or caller.company_name_claimed,
        "company_verification_status": caller.verification_status,
        "contact_known": contact_is_known,
        "caller_type": caller.caller_type,
        "previous_calls": history.total_calls,
        "calls_today": history.calls_last_24h,
        "last_call_timestamp": getattr(history, "last_call_timestamp", None) or now_iso,
        "initial_risk": risk_assessment.score,
        "risk_level": risk_assessment.level,
        "recommended_action": recommended_action,
        "current_action": recommended_action,
        "speaker_verification_status": "WAITING",
        "deepfake_detection_status": "WAITING",
        "liveness_status": "WAITING",
        "voice_activity": "NO_AUDIO_YET",
        "cellular_audio_available": cellular_audio_avail,
        "call_transport": payload.call_transport.upper(),
        "call_status": "RINGING",
        "status": "RINGING",
        "timestamp": now_iso,
        "threat_signals": risk_assessment.reasons,
        "audio_stream_active": False,
        "user_id": payload.user_id,
        "device_id": payload.device_id,
    }

    # Store in memory event bus
    dashboard_event_bus.set_active_call(call_id, call_session_data)

    # Persist call session to Supabase public.calls & public.call_actions immediately
    try:
        await call_record_service.record_screening_call(
            session_id=call_id,
            phone_number=raw_number,
            normalized_number=normalized,
            caller_id=caller.id,
            caller_name=caller_display,
            company_name=caller.company,
            company_verified=caller.company_verified,
            company_name_claimed=caller.company_name_claimed,
            company_name_verified=caller.company_name_verified,
            verification_source=caller.verification_source,
            verification_status=caller.verification_status,
            relationship=caller.relationship,
            relationship_verified=caller.relationship_verified,
            caller_type=caller.caller_type,
            previous_calls_count=history.total_calls,
            calls_last_1h=history.calls_last_1h,
            calls_last_24h=history.calls_last_24h,
            calls_last_7d=history.calls_last_7d,
            average_call_duration=history.average_call_duration_sec,
            failed_verifications=history.failed_verifications,
            suspicious_calls=history.suspicious_events,
            blocked_calls=history.blocked_calls,
            risk_score=risk_assessment.score,
            risk_level=risk_assessment.level,
            action_taken=recommended_action,
            action_reason="; ".join(risk_assessment.reasons),
            model_version="v1.0-vigil-telephony",
            user_id=payload.user_id
        )
    except Exception as e:
        logger.warning(f"Could not persist call record to Supabase: {e}")

    # BROADCAST TO LAPTOP DASHBOARD IMMEDIATELY VIA WEBSOCKET (with user_id isolation)
    await dashboard_event_bus.broadcast_event(
        event_type="incoming_call",
        payload={
            "call_id": call_id,
            "phone_number": raw_number,
            "normalized_phone_number": normalized,
            "masked_phone": masked_phone,
            "caller_name": caller_display,
            "company": caller.company or caller.company_name_claimed,
            "company_verification_status": caller.verification_status,
            "contact_known": contact_is_known,
            "caller_type": caller.caller_type,
            "previous_calls": history.total_calls,
            "calls_today": history.calls_last_24h,
            "last_call_timestamp": history.last_call_timestamp or now_iso,
            "initial_risk": risk_assessment.score,
            "risk_level": risk_assessment.level,
            "recommended_action": recommended_action,
            "speaker_verification_status": "WAITING",
            "deepfake_detection_status": "WAITING",
            "liveness_status": "WAITING",
            "cellular_audio_available": cellular_audio_avail,
            "call_transport": payload.call_transport.upper(),
            "timestamp": now_iso,
            "threat_signals": risk_assessment.reasons,
        },
        call_id=call_id,
    )

    try:
        from app.api.v1.endpoints.screening import record_live_screened_call
        record_live_screened_call({
            "timestamp": now_iso,
            "phone_number": raw_number,
            "normalized_number": normalized,
            "masked_phone": masked_phone,
            "caller_name": caller_display,
            "company_name": caller.company or caller.company_name_claimed,
            "company_badge": None,
            "verification_status": caller.verification_status,
            "trust_status": caller.trust_status,
            "risk_score": risk_assessment.score,
            "risk_level": risk_assessment.level,
            "action": recommended_action,
            "reasons": risk_assessment.reasons,
            "voice_deepfake_pct": 0,
            "voice_identity_pct": 0,
            "voice_liveness_pct": 0,
            "warning_banner": None,
            "calls_summary_total": history.total_calls,
            "calls_summary_today": history.calls_last_24h,
            "call_id": call_id,
            "user_id": payload.user_id,
            "target_phone": payload.user_id or "Registered Device",
            "subscriber_phone": payload.user_id or "Registered Device",
        })
    except Exception as e:
        logger.debug(f"Could not record live screened call: {e}")

    return IncomingCallResponse(**call_session_data)

