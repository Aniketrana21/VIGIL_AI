@router.post("/{call_id}/action")
async def execute_call_action(call_id: str, act: CallActionRequest):
    """Executes a policy action (ALLOW, MONITOR, CHALLENGE, WARN, SILENCE, BLOCK, TERMINATE)."""
    action_upper = act.action.upper()
    now_iso = datetime.now(timezone.utc).isoformat()

    active = dashboard_event_bus.get_active_call(call_id)
    if active:
        active["current_action"] = action_upper
        active["action"] = action_upper
        active["call_status"] = "BLOCKED" if action_upper in ["BLOCK", "TERMINATE"] else ("WARNED" if action_upper == "WARN" else "MONITORING")

    event_name = "call_terminated" if action_upper == "TERMINATE" else ("call_blocked" if action_upper == "BLOCK" else "warning_issued")
    user_id = active.get("user_id") if active else None

    await dashboard_event_bus.broadcast_event(
        event_type=event_name,
        payload={
            "action": action_upper,
            "reason": act.reason,
            "risk_score": act.risk_score or 100,
            "triggered_by": act.triggered_by,
        },
        call_id=call_id,
        user_id=user_id
    )

    # Persist action to public.call_actions
    pool = await get_db_pool()
    if pool:
        try:
            async with pool.acquire() as conn:
                call_row = await conn.fetchrow("SELECT id FROM public.calls WHERE session_id = $1 LIMIT 1", call_id)
                if call_row:
                    await conn.execute("""
                        INSERT INTO public.call_actions (
                            call_id, action, reason, risk_score, triggered_by
                        ) VALUES ($1, $2, $3, $4, $5)
                    """, call_row["id"], action_upper, act.reason, act.risk_score or 100, act.triggered_by)
                    await conn.execute("""
                        UPDATE public.calls SET final_action = $2, call_status = $3 WHERE id = $1
                    """, call_row["id"], action_upper, "blocked" if action_upper in ["BLOCK", "TERMINATE"] else "in_progress")
        except Exception as e:
            logger.warning(f"Error persisting call action: {e}")

    return {"status": "enforced", "call_id": call_id, "action": action_upper}

