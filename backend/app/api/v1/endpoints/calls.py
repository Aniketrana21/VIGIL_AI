ws_router = APIRouter()

@ws_router.websocket("/ws/dashboard")
@router.websocket("/ws/dashboard")
async def websocket_dashboard_feed(websocket: WebSocket, user_id: Optional[str] = Query(None)):
    """
    Real-Time Laptop SOC Dashboard WebSocket Feed with per-user tenant isolation.
    Zero-polling live event pipeline: receives incoming_call, risk_update,
    live telemetry, and automatic termination events for the active user account.
    """
    await websocket.accept()
    await dashboard_event_bus.register_dashboard_client(websocket, user_id=user_id)

    # Send initial snapshot of active calls for this specific user
    try:
        active_calls = dashboard_event_bus.get_all_active_calls(user_id=user_id)
        await websocket.send_json({
            "event": "system_status",
            "user_id": user_id,
            "backend": "ONLINE",
            "database": "ONLINE",
            "ai_service": "ONLINE",
            "websocket": "CONNECTED",
            "cellular_monitoring": "PRE_CALL_SCREENING_ONLY",
            "voip_monitoring": "REAL_TIME_AUDIO_AND_AUTO_TERMINATE",
            "active_calls_count": len(active_calls),
            "active_calls": active_calls,
            "timestamp": datetime.now(timezone.utc).isoformat()
        })
    except Exception as e:
        logger.debug(f"Error sending dashboard handshake: {e}")

    try:
        while True:
            data = await websocket.receive_text()
            try:
                import json
                msg = json.loads(data)
                if str(msg.get("type", "")).upper() == "PING":
                    await websocket.send_json({"type": "pong", "timestamp": msg.get("timestamp")})
            except Exception:
                pass
    except (WebSocketDisconnect, RuntimeError):
        pass
    finally:
        await dashboard_event_bus.unregister_dashboard_client(websocket, user_id=user_id)

