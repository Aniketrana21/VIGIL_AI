class IncomingCallRequest(BaseModel):
    call_id: Optional[str] = Field(None, description="Unique call identifier if generated by client")
    phone_number: str = Field(..., description="Raw caller phone number")
    caller_name: Optional[str] = Field(None, description="Caller display name from device contact book")
    company_name: Optional[str] = Field(None, description="Claimed corporate affiliation")
    contact_match: Optional[bool] = Field(False, description="Whether number matched device address book")
    contact_known: Optional[bool] = Field(None, description="Whether caller is known contact")
    caller_type: Optional[str] = Field(None, description="Caller category")
    stir_shaken_status: Optional[int] = Field(0, description="0=Unverified, 1=Passed, 2=Failed")
    carrier_code: Optional[str] = Field(None, description="Network carrier code")
    device_id: Optional[str] = Field("android_device_primary", description="Reporting mobile device ID")
    user_id: Optional[str] = Field(None, description="VIGIL-AI account user ID")
    call_direction: str = Field("INCOMING", description="Call direction")
    claimed_relationship: Optional[str] = Field(None, description="e.g. FRIEND, FAMILY, BANK")
    call_transport: str = Field("CELLULAR", description="CELLULAR or VOIP")

class IncomingCallResponse(BaseModel):
    call_id: str
    phone_number: str
    normalized_phone_number: str
    masked_phone: str
    caller_name: str
    company: Optional[str]
    company_verification_status: str
    contact_known: bool
    caller_type: str
    previous_calls: int
    calls_today: int
    last_call_timestamp: Optional[str]
    initial_risk: int
    risk_level: str
    recommended_action: str
    status: str = "RINGING"
    call_status: str = "RINGING"
    speaker_verification_status: str  # WAITING | ANALYZING | VERIFIED | MISMATCH
    deepfake_detection_status: str     # WAITING | ANALYZING | CLEAN | SYNTHETIC
    liveness_status: str               # WAITING | ANALYZING | LIVE | REPLAY
    cellular_audio_available: bool     # False for standard Android cellular
    timestamp: str

class CallAnalysisRequest(BaseModel):
    window_start_ms: int = 0
    window_end_ms: int = 2000
    deepfake_probability: float
    bonafide_probability: Optional[float] = None
    speaker_similarity: Optional[float] = None
    liveness_score: Optional[float] = None
    replay_probability: Optional[float] = None
    confidence: float = 0.95
    uncertainty: Optional[float] = 0.0
    voice_activity: Optional[str] = None
    signal_quality: Optional[str] = "GOOD"
    vad_speech_detected: bool = True
    transcript_segment: Optional[str] = None

class CallRiskUpdateRequest(BaseModel):
    risk_score: int
    risk_level: str
    signals: List[str] = []
    contributing_signals: List[str] = []
    action: str = "MONITOR"
    reason: str = "Risk update"
    confidence: float = 0.95

class CallActionRequest(BaseModel):
    action: str = Field(..., description="ALLOW | MONITOR | CHALLENGE | WARN | SILENCE | BLOCK | TERMINATE")
    reason: str = Field(..., description="Human or algorithmic justification")
    risk_score: Optional[int] = None
    triggered_by: str = Field("policy_engine", description="risk_engine | soc_operator | policy_engine")

class TerminateCallRequest(BaseModel):
    reason: str = Field("Critical fraud threat detected: automatic call termination enforced", description="Termination rationale")
    risk_score: Optional[int] = 100
    deepfake_probability: Optional[float] = None
    speaker_similarity: Optional[float] = None
    signals: Optional[List[str]] = None

